export function emoCat(lang: EmoLang, koName: string): string {
  if (lang === 'ko') return koName
  return CATS[lang][koName] || koName
}

export function emoLabel(lang: EmoLang, id: string, koLabel: string): string {
  if (lang === 'ko') return koLabel
  return LABELS[lang][id] || koLabel
}

export function currentEmoLang(): EmoLang {
  const lang = (window.__dawonI18n?.lang || localStorage.getItem('dawon_lang_v1') || 'ko') as string
  return lang === 'en' || lang === 'ja' || lang === 'zh' ? lang : 'ko'
}
